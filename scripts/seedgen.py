#!/usr/bin/env python3
"""Convert graphify-out/graph.json (the AEiG code knowledge graph) into an
AEiG-schema seed the app can serve:

  seed/aeig-code-graph.sql     — Postgres: one row in `graphs`
  seed/aeig-code-graph.cypher  — Neo4j: :Element nodes + :REL edges (graphId-scoped)

Node `type` is derived from the source module (service, httpapi, domain, pg,
neo4j, config, cmd, fe-graph, fe-api, fe-app, fe-test, code). Idempotent
(MERGE / ON CONFLICT). Regenerate with `make seed-regen`.
"""
import json
import pathlib

GRAPH_ID = "c0de0000-0000-4000-8000-000000000001"
GRAPH_NAME = "AEiG code graph (graphify)"

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "graphify-out" / "graph.json"
OUT = ROOT / "seed"


def node_type(source_file: str) -> str:
    p = (source_file or "").split("/")
    if not p or not p[0]:
        return "code"
    if p[0] == "backend":
        if len(p) >= 2 and p[1] == "cmd":
            return "cmd"
        if len(p) >= 3 and p[1] == "internal":
            pkg = p[2]
            if pkg == "storage" and len(p) >= 4:
                return {"postgres": "pg", "neo4j": "neo4j"}.get(p[3], "storage")
            return pkg  # config, domain, service, httpapi
        return "backend"
    if p[0] == "frontend":
        if len(p) >= 3 and p[1] == "src":
            area = p[2]
            if area == "graph":
                return "fe-graph"
            if area == "api":
                return "fe-api"
            if area == "test":
                return "fe-test"
            return "fe-app"  # App.tsx, main.tsx, etc.
        return "frontend"
    return "code"


def cy_str(v) -> str:
    """Cypher single-quoted string literal."""
    s = "" if v is None else str(v)
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n").replace("\r", "")
    return f"'{s}'"


def cy_props(d: dict) -> str:
    parts = []
    for k, v in d.items():
        if isinstance(v, bool):
            parts.append(f"{k}: {'true' if v else 'false'}")
        elif isinstance(v, (int, float)):
            parts.append(f"{k}: {v}")
        else:
            parts.append(f"{k}: {cy_str(v)}")
    return "{" + ", ".join(parts) + "}"


def main() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    nodes = data.get("nodes", [])
    edges = data.get("links", [])
    OUT.mkdir(exist_ok=True)

    # --- Postgres row ---
    sql = (
        "-- Generated by scripts/seedgen.py from graphify-out/graph.json. Do not edit by hand.\n"
        "INSERT INTO graphs (id, name) VALUES\n"
        f"  ('{GRAPH_ID}', {pg_str(GRAPH_NAME)})\n"
        "ON CONFLICT (id) DO NOTHING;\n"
    )
    (OUT / "aeig-code-graph.sql").write_text(sql, encoding="utf-8")

    # --- Neo4j elements ---
    node_rows = []
    for n in nodes:
        nid = n["id"]
        typ = node_type(n.get("source_file", ""))
        props = {
            "label": n.get("norm_label") or n.get("label") or nid,
            "file": n.get("source_file", ""),
            "loc": n.get("source_location", ""),
            "community": n.get("community_name", ""),
        }
        node_rows.append(f"  {{id: {cy_str(nid)}, type: {cy_str(typ)}, props: {cy_props(props)}}}")

    edge_rows = []
    for i, e in enumerate(edges):
        eid = f"e{i}"
        props = {"weight": float(e.get("weight", 1.0)), "confidence": e.get("confidence", "")}
        edge_rows.append(
            f"  {{id: {cy_str(eid)}, type: {cy_str(e.get('relation', 'rel'))}, "
            f"source: {cy_str(e['source'])}, target: {cy_str(e['target'])}, props: {cy_props(props)}}}"
        )

    gid = cy_str(GRAPH_ID)
    cypher = (
        "// Generated by scripts/seedgen.py from graphify-out/graph.json. Do not edit by hand.\n"
        f"UNWIND [\n{','.join(chr(10) + r for r in node_rows)}\n] AS n\n"
        f"MERGE (x:Element {{graphId: {gid}, id: n.id}})\n"
        "SET x.type = n.type, x += n.props;\n\n"
        f"UNWIND [\n{','.join(chr(10) + r for r in edge_rows)}\n] AS e\n"
        f"MATCH (s:Element {{graphId: {gid}, id: e.source}})\n"
        f"MATCH (t:Element {{graphId: {gid}, id: e.target}})\n"
        f"MERGE (s)-[r:REL {{graphId: {gid}, id: e.id}}]->(t)\n"
        "SET r.type = e.type, r += e.props;\n"
    )
    (OUT / "aeig-code-graph.cypher").write_text(cypher, encoding="utf-8")

    print(f"seed: {len(nodes)} nodes, {len(edges)} edges -> {OUT}/ (graphId={GRAPH_ID})")


def pg_str(v: str) -> str:
    return "'" + str(v).replace("'", "''") + "'"


if __name__ == "__main__":
    main()
